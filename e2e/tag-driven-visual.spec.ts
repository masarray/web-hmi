import {test,expect} from '@playwright/test';

test('bound motor fails closed and resumes rotor only for GOOD active data',async({page})=>{
  await page.goto('/');
  await page.getByRole('searchbox',{name:'Search symbols'}).fill('motor');
  await page.getByRole('button',{name:'Add Motor Simb SVG symbol'}).click();
  await page.getByRole('combobox',{name:'Symbol animation'}).selectOption('spin');
  await page.getByLabel('Tag identifier').fill('Pump/Motor');
  await page.getByLabel('Tag identifier').press('Tab');
  const motor=page.locator('g.canvas-node').last();
  await page.getByRole('button',{name:/Preview/}).click();
  await expect(page.getByTestId('simulation-bar')).toContainText('SIMULATION ONLY');
  await expect(motor).toHaveAttribute('data-visual-quality','STALE');
  await expect(motor.locator('g.process-rotor')).toHaveCount(0);
  await expect(motor.locator('.visual-quality-indicator text')).toHaveText('STALE');
  await page.getByRole('button',{name:'Set ON'}).click();
  await expect(motor).toHaveAttribute('data-visual-status','ACTIVE');
  await expect(motor.locator('g.process-rotor')).toHaveCount(1);
  await page.getByRole('combobox',{name:'Simulation quality'}).selectOption('BAD');
  await expect(motor).toHaveAttribute('data-visual-quality','BAD');
  await expect(motor.locator('g.process-rotor')).toHaveCount(0);
  await expect(motor.locator('.visual-quality-indicator text')).toHaveText('BAD');
  await page.getByRole('combobox',{name:'Simulation quality'}).selectOption('UNCERTAIN');
  await expect(motor).toHaveAttribute('data-visual-quality','UNCERTAIN');
  await page.getByRole('combobox',{name:'Simulation quality'}).selectOption('STALE');
  await expect(motor).toHaveAttribute('data-visual-quality','STALE');
  await page.getByRole('combobox',{name:'Simulation quality'}).selectOption('GOOD');
  await expect(motor.locator('g.process-rotor')).toHaveCount(1);
  await page.getByRole('button',{name:'Set OFF'}).click();
  await expect(motor).toHaveAttribute('data-visual-status','IDLE');
  await expect(motor.locator('g.process-rotor')).toHaveCount(0);
});

test('threshold visual rule and numeric simulation survive project save',async({page})=>{
  await page.goto('/');
  await page.getByRole('searchbox',{name:'Search symbols'}).fill('pumpgear');
  await page.getByRole('button',{name:'Add Pumpgear SVG symbol'}).click();
  await page.getByRole('combobox',{name:'Symbol animation'}).selectOption('spin');
  await page.getByLabel('Tag identifier').fill('Pump/Pressure');
  await page.getByLabel('Tag identifier').press('Tab');
  await page.getByRole('combobox',{name:'Visual activation rule'}).selectOption('at-least');
  await page.getByRole('spinbutton',{name:'Visual threshold'}).fill('10');
  await page.getByRole('spinbutton',{name:'Visual threshold'}).press('Tab');
  await page.getByRole('button',{name:/Preview/}).click();
  const pump=page.locator('g.canvas-node').last();
  await page.getByRole('button',{name:'Set ON'}).click();
  await expect(pump).toHaveAttribute('data-visual-status','IDLE');
  await page.getByRole('spinbutton',{name:'Simulated numeric value'}).fill('12');
  await page.getByRole('spinbutton',{name:'Simulated numeric value'}).press('Tab');
  await expect(pump).toHaveAttribute('data-visual-status','ACTIVE');
  await expect(pump.locator('g.process-rotor')).toHaveCount(2);
  await page.reload();
  await page.locator('g.canvas-node').last().click();
  await expect(page.getByRole('combobox',{name:'Visual activation rule'})).toHaveValue('at-least');
  await expect(page.getByRole('spinbutton',{name:'Visual threshold'})).toHaveValue('10');
  await page.getByRole('button',{name:/Preview/}).click();
  await expect(page.locator('g.canvas-node').last()).toHaveAttribute('data-visual-quality','STALE');
});

test('simulated tags update independently and do not write sample state into export',async({page})=>{
  await page.goto('/');
  await page.getByRole('searchbox',{name:'Search symbols'}).fill('motor');
  await page.getByRole('button',{name:'Add Motor Simb SVG symbol'}).click();
  const shapes=page.locator('g.canvas-node');
  await expect(shapes).toHaveCount(12);
  await expect(page.locator('.layers button').last()).toHaveAttribute('aria-pressed','true');
  await page.getByLabel('Tag identifier').fill('Pump/A');
  await page.getByLabel('Tag identifier').press('Tab');
  await expect(page.locator('.layers button').last().locator('.tag-mark')).toBeVisible();
  await page.getByRole('button',{name:'Add Motor Simb SVG symbol'}).click();
  await expect(shapes).toHaveCount(13);
  await expect(page.locator('.layers button').last()).toHaveAttribute('aria-pressed','true');
  await page.getByLabel('Tag identifier').fill('Pump/B');
  await page.getByLabel('Tag identifier').press('Tab');
  await expect(page.locator('.layers button').last().locator('.tag-mark')).toBeVisible();
  const a=shapes.nth(11),b=shapes.nth(12);
  await page.getByRole('button',{name:/Preview/}).click();
  await expect(page.getByRole('combobox',{name:'Simulation tag'}).locator('option')).toHaveCount(2);
  await page.getByRole('combobox',{name:'Simulation tag'}).selectOption('Pump/A');
  await page.getByRole('button',{name:'Set ON'}).click();
  await expect(a).toHaveAttribute('data-visual-quality','GOOD');
  await expect(b).toHaveAttribute('data-visual-quality','STALE');
  await page.getByRole('combobox',{name:'Simulation tag'}).selectOption('Pump/B');
  await page.getByRole('combobox',{name:'Simulation quality'}).selectOption('BAD');
  await expect(a).toHaveAttribute('data-visual-quality','GOOD');
  await expect(b).toHaveAttribute('data-visual-quality','BAD');
  await page.getByRole('button',{name:/Exit Preview/}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/Export/}).click();
  const download=await downloadPromise;
  const stream=await download.createReadStream();
  let body='';
  for await (const chunk of stream) body+=chunk.toString();
  expect(body).not.toContain('"sequence"');
  expect(body).not.toContain('"quality"');
  expect(body).toContain('"tagId": "Pump/A"');
});
